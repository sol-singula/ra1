-- the mastery track an item counts toward
function Items.masteryClass(item)
	if not item then
		return nil
	end
	if item.class then
		return item.class
	end
	if item.kind == "trap" or item.kind == "throw" then
		return "trap"
	end
	if item.kind == "support" or item.kind == "food" then
		return "support"
	end
	return nil
end

function Items.get(key)
	return Items.byKey[key]
end

function Items.isEquipment(item)
	return item ~= nil and (item.kind == "armor" or item.kind == "pack" or item.kind == "charm")
end

-- Items that go to the hotbar first when picked up (things you hold); the rest go to the backpack.
function Items.goesToHotbar(item)
	local k = item and item.kind
	return k == "weapon" or k == "light" or k == "trap" or k == "throw" or k == "support" or k == "food"
end

function Items.rarityColor(rarity)
	local r = Items.RARITY[rarity]
	return r and r.color or Items.RARITY.common.color
end

return Items
