(they're gone when it ends); discovering an item for the first time is kept forever in your collection log.

  kind      resource | food | weapon | ammo | trap | throw | support | light | armor | pack | charm | key
  rarity    common | uncommon | rare | epic | legendary (§6: a small, readable ladder)
  stack     how many fit in one slot (1 when missing)

Weapons (§5: each has a role and a trade-off; rarity doesn't make older ones worthless):
  class     axe | club | spear | bow
  dmg, cd   damage per hit and seconds between hits
  range,arc reach (studs) and the swing's width (degrees)
  tree,rock how well it chops trees / breaks rocks (x10 damage to them)
  stagger   0-3: a stagger stops a heavy monster's wind-up (clubs)
