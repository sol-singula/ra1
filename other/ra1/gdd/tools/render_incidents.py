#!/usr/bin/env python3
"""Render section 36.9 (Offline Incidents Database) from gdd/data/offline_incidents.json.

Python 3 stdlib only, idempotent:  python3 gdd/tools/render_incidents.py
The same JSON rows drive gdd/tools/offline_sim_examples.py (eligibility, weights, effects, caps).
"""
import json
import os
import sys
from collections import Counter

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import a11_canon as C  # noqa: E402

DATA = json.load(open(os.path.join(C.DATA, "offline_incidents.json"), encoding="utf-8"))["incidents"]
OUT = os.path.join(C.SECTIONS, "36_09_offline_incidents.md")
CATS = ["customer", "damage", "equipment", "staff", "supply", "demand", "inspection", "celebrity", "hero",
        "discovery", "weird"]
SIGN = {"+": "+", "-": "−", "0": "0"}


def num(x):
    return ("%+.2f" % x).replace("-", "−")


def effect(i):
    parts = []
    if "mb" in i:
        parts.append("%s·Rh" % num(i["mb"]))
    if "dmg" in i:
        parts.append("damage %.2f·Rh" % i["dmg"])
    if "stock" in i:
        parts.append("special stock %s %%" % num(100 * i["stock"]).replace(".00", ""))
    if "stock_units" in i:
        parts.append("special stock +%d units" % i["stock_units"])
    if "morale" in i:
        v, scope = i["morale"]
        parts.append("Morale %s (%s)" % (("%+d" % v).replace("-", "−"), scope))
    if "rep" in i:
        parts.append("%s ★" % num(i["rep"]))
    if "ms" in i:
        parts.append("+%d–%d MS" % tuple(i["ms"]))
    if "crate" in i:
        parts.append("crate of %d–%d special units" % tuple(i["crate"]))
    if "capsule" in i:
        parts.append("+1 Morph Capsule")
    if i["id"] == "INC_031":
        parts.append("(−0.02·Rh instead if no special stock)")
    if i["id"] == "INC_059":
        parts.append("(+0.02·Rh instead if no special recipe)")
    if i.get("cancels"):
        parts.append("cancels 1 %s incident" % i["cancels"])
    return "; ".join(parts) if parts else "flavor only (0 MB)"


def mitig(i):
    out = []
    for m in i["mitig_text"]:
        out.append("`%s`" % m if m.startswith("ROLE_") else m)
    return ", ".join(out)


def main():
    ids = [i["id"] for i in DATA]
    assert len(ids) == len(set(ids))
    drawable = [i for i in DATA if i["cat"] != "discovery"]
    for i in DATA:
        assert i["cat"] in CATS, i["id"]
        assert i["sign"] in SIGN
        neg = i.get("mb", 0) < 0 or i.get("dmg", 0) > 0 or i.get("stock", 0) < 0
        if i["sign"] == "+":
            assert i.get("mb", 0) >= 0, i["id"]
        if neg and i["cat"] not in ("demand", "celebrity", "weird"):
            assert i["sign"] == "-", i["id"]
    L = []
    w = L.append
    w("### 36.9 Offline Incidents Database")
    w("")
    w("> Generated by `python3 gdd/tools/render_incidents.py` from `gdd/data/offline_incidents.json`. The same rows "
      "drive the reference simulator `gdd/tools/offline_sim_examples.py` and must be mirrored 1:1 in the Luau data "
      "module `ReplicatedStorage.Shared.Data.OfflineIncidents` (golden test, §17).")
    w("")
    w("**%d incidents**: %d drawable by the incident roll plus %d *discovery dressings* (they never use the incident "
      "count; they narrate the separate Discoveries rolls of §17). Weights, effect magnitudes and ranges are **[TUNABLE]**; "
      "the caps are canon. Rules that apply to every row:" % (
          len(DATA), len(drawable), len(DATA) - len(drawable)))
    w("")
    w("- **Count** (canon §C15): `count = floor(H × 0.6 × (1 − SecurityMitigation)) + seeded extra roll`, where H is "
      "the interval's *effective* hours after the long-absence taper (§17.4: hours 0–2 ×1.0, 2–8 ×0.5, 8–24 ×0.2); each "
      "draw picks one eligible row by effective weight. An incident ID appears at most twice per report; draws are "
      "assigned to a random operated step.")
    w("- **Rh** = Revenue + Tips + Delivery of the interval per effective hour, before incidents. Expressing effects in "
      "Rh keeps every row meaningful from `TIER_01` to `TIER_10` and makes the total scale with activity, never with tier.")
    w("- **Damage x·Rh** is a repair bill converted to damage points on random destructible objects "
      "(`points = ceil(x·Rh / CostPerPoint[tier])`, §17). It is auto-paid at a discount if a `ROLE_REPAIR` works "
      "offline, otherwise left as visibly damaged objects for the player (Restaurant Damage tab). Damage never "
      "destroys an object (offline damage stops at Broken; §C6 objects are never lost).")
    w("- **Caps** (canon §C15): Σ negative effects (MB losses + damage value) ≤ **10 %** of interval Revenue + Tips; "
      "Σ positive MB ≤ **15 %**; excess is scaled down proportionally. An assigned `ROLE_ASST_MGR` multiplies "
      "negative magnitudes by **0.8** (canon −20 %); a Security Guard with *Tough Shell* multiplies customer-category "
      "negatives by 0.9.")
    w("- **Mitigated by** (negative rows): each listed role present scales the weight by "
      "`max(0.4, 1 − 0.6 × min(1, best Contribution of that role))`; listed traits apply the stated weight "
      "multiplier. **Hero** rows *require* the role and scale weight by `0.5 + min(1, best Contribution)`.")
    w("- **Reputation** changes are clamped to ±0.05 ★ per report; Morale changes apply to the end-of-interval "
      "values (scope `subject` = the employee named in the line, `all` = everyone who worked, `chefs`).")
    w("- **Report text** tokens: `{employee}` = the relevant employee's short name (highest offline Contribution in "
      "the subject role, fallback Manager → Chef → \"the team\"); `{n}` = a seeded integer in the row's range. Lines "
      "are kid-safe and never blame the player.")
    w("")
    w("**Category coverage** (brief Part 11.9 → categories)")
    w("")
    cnt = Counter(i["cat"] for i in DATA)
    signs = {c: Counter(i["sign"] for i in DATA if i["cat"] == c) for c in CATS}
    brief = {"customer": "angry customers", "damage": "broken furniture", "equipment": "kitchen equipment failure",
             "staff": "employee mistakes", "supply": "ingredient shortages", "demand": "unexpected rushes",
             "inspection": "surprise inspections", "celebrity": "celebrity customers", "hero": "employee hero moments",
             "discovery": "rare mutation discoveries", "weird": "(bonus) city weirdness"}
    w("| Category | Brief item | Rows | + | − | 0 |")
    w("|---|---|---|---|---|---|")
    for c in CATS:
        w("| %s | %s | %d | %d | %d | %d |" % (c, brief[c], cnt[c], signs[c]["+"], signs[c]["-"], signs[c]["0"]))
    w("| **Total** | | **%d** | %d | %d | %d |" % (len(DATA), sum(1 for i in DATA if i["sign"] == "+"),
                                                   sum(1 for i in DATA if i["sign"] == "-"),
                                                   sum(1 for i in DATA if i["sign"] == "0")))
    w("")
    w("#### 36.9.1 Incident table")
    w("")
    w("| ID | Name | Category | Trigger / conditions | Weight | Effect (formula) | Mitigated by | Report text | Sign |")
    w("|---|---|---|---|---|---|---|---|---|")
    for i in DATA:
        w("| `%s` | %s | %s | %s | %s | %s | %s | %s | %s |" % (
            i["id"], i["name"], i["cat"], i["trigger"], i["weight"], effect(i), mitig(i),
            i["text"].replace("|", "/"), SIGN[i["sign"]]))
    w("")
    w("#### 36.9.2 Authoring rules for new incidents")
    w("")
    w("1. Use the next free `INC_` number; never reuse an ID. Category must be one of the eleven above.")
    w("2. A single row's |MB| ≤ 0.10·Rh and damage ≤ 0.08·Rh, so no single draw can approach the 10 % interval cap "
      "on a short (≥ 1 h) report.")
    w("3. Every negative row lists at least one mitigation (a role, a trait, or \"hire a …\") so the Welcome Back screen "
      "can turn it into an Upgrade Suggestion (§17).")
    w("4. Conditions may only read the simulation snapshot (tier, ★, roster roles/traits/personalities, menu stations, "
      "special stock, capacity headroom, offline quality q, Energy/Morale minima, UTC hour, scheduled `EVT_` overlap from "
      "`CityEventService`) — never live server state — so reports stay deterministic.")
    w("5. Text: one or two sentences, ≤ 140 characters after token substitution, cartoon consequences only (soot, "
      "confetti, feathers, sauce), no real brands or people.")
    w("")
    txt = "\n".join(L)
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(txt)
    print("wrote %s (%d bytes, %d incidents, %d drawable)" % (OUT, len(txt.encode("utf-8")), len(DATA), len(drawable)))


if __name__ == "__main__":
    main()
