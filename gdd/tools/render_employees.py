#!/usr/bin/env python3
"""Render section 36.8 (Employee Archetypes Database) from gdd/data/employees.json.

Python 3 stdlib only, idempotent:  python3 gdd/tools/render_employees.py
Validates every row against canon C4.8 bands, C13.6 parts/slots and the trait
derivation keys (families/tags) before writing
gdd/sections/36_08_employee_archetypes.md.
"""
import json
import os
import sys
from collections import Counter

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import a11_canon as C  # noqa: E402

MUT = C.mutations()
BANDS = C.rarity_bands()
TIERS = C.tiers()
DATA = json.load(open(os.path.join(C.DATA, "employees.json"), encoding="utf-8"))
OUT = os.path.join(C.SECTIONS, "36_08_employee_archetypes.md")

ROLE_NAME = {"ROLE_CHEF": "Chef", "ROLE_PREP": "Prep Cook", "ROLE_WAITER": "Waiter", "ROLE_CASHIER": "Cashier",
             "ROLE_DISH": "Dishwasher", "ROLE_CLEANER": "Cleaner", "ROLE_REPAIR": "Repair Technician",
             "ROLE_SECURITY": "Security Guard", "ROLE_MANAGER": "Restaurant Manager",
             "ROLE_DELIVERY": "Delivery Worker", "ROLE_STOCKER": "Ingredient Stocker",
             "ROLE_ASST_MGR": "Assistant Manager"}
RARITIES = ["Common", "Uncommon", "Rare", "Epic", "Legendary"]
ICON = {"Common": "●", "Uncommon": "▲", "Rare": "■", "Epic": "⬟", "Legendary": "★"}


def derivable(trait, parts):
    k = DATA["traits"][trait]
    fams = [MUT[p]["family"] for p in parts]
    if any(f in k.get("families", []) for f in fams):
        return True
    if "slot_tag" in k:
        slots, tag = k["slot_tag"]
        if any(MUT[p]["slot"] in slots and tag in MUT[p]["tags"] for p in parts):
            return True
    if "any_tag" in k and any(k["any_tag"] in MUT[p]["tags"] for p in parts):
        return True
    if "tag" in k:
        cnt = sum(1 for p in parts if k["tag"] in MUT[p]["tags"])
        if cnt >= k["min"] and not (k.get("no_tag") and any(k["no_tag"] in MUT[p]["tags"] for p in parts)):
            return True
    if "tag2" in k:
        if sum(1 for p in parts if any(t in MUT[p]["tags"] for t in k["tag2"])) >= k["min"]:
            return True
    return False


def validate():
    errs = []
    seen = set()
    for a in DATA["archetypes"]:
        if a["id"] in seen:
            errs.append((a["id"], "duplicate"))
        seen.add(a["id"])
        b = BANDS[a["rarity"]]
        if a["id"] != "EMP_001":
            if not (b["hire"][0] <= a["hire"] <= b["hire"][1]):
                errs.append((a["id"], "hire", a["hire"]))
            if not (b["wage"][0] <= a["wage"] <= b["wage"][1]):
                errs.append((a["id"], "wage", a["wage"]))
        for s, v in a["stats"].items():
            if not (b["stat"][0] <= v <= b["stat"][1]):
                errs.append((a["id"], "stat", s, v))
        slots = Counter(MUT[p]["slot"] for p in a["parts"])
        for s, n in slots.items():
            if n > (2 if s in ("ARM", "LEG") else 1):
                errs.append((a["id"], "slot", s))
        for t in a["traits"]:
            if not derivable(t, a["parts"]):
                errs.append((a["id"], "trait", t))
        if a["potential_cap"] != b["cap"]:
            errs.append((a["id"], "cap"))
    e1 = next(a for a in DATA["archetypes"] if a["id"] == "EMP_001")
    canon_e1 = {"cook": 30, "svc": 15, "acc": 28, "rel": 40}
    if any(e1["stats"][k] != v for k, v in canon_e1.items()) or e1["wage"] != 12 or e1["hire"] != 0 \
            or e1["role"] != "ROLE_CHEF" or e1["rarity"] != "Common":
        errs.append(("EMP_001", "canon C14.4 mismatch"))
    return errs


def morph_cell(parts):
    c = Counter(parts)
    seen, out = set(), []
    for p in parts:
        if p in seen:
            continue
        seen.add(p)
        n = c[p]
        out.append("`%s` %s%s" % (p, MUT[p]["name"], " ×2" if n == 2 else ""))
    return " + ".join(out)


def money(v):
    return "{:,}".format(v)


def main():
    errs = validate()
    if errs:
        print("VALIDATION FAILED:", errs)
        sys.exit(1)
    arch = DATA["archetypes"]
    L = []
    w = L.append
    w("### 36.8 Employee Archetypes Database")
    w("")
    w("> Generated by `python3 gdd/tools/render_employees.py` from `gdd/data/employees.json` — edit the JSON, "
      "never this file. The renderer validates every row against canon §C4.8 (hire, wage, stat band, potential "
      "cap), §C13.6 (parts, slots, families, tags) and the trait-derivation keys of §16 before writing.")
    w("")
    w("This database lists **%d employee archetypes** (`EMP_001` is fixed by canon §C14.4; `EMP_002`+ are defined "
      "here). An archetype is a *template*: the Recruitment Office (§16) rolls individual candidates from it with "
      "small seeded variance (stats ±3, hire ±10 %%, wage ±10 %%, always clamped inside the rarity band) and a "
      "random quirk line. Formulas that consume these columns (Efficiency, offline contribution, training, "
      "morale) live in §16 and §17; incidents that reference traits live in §36.9." % len(arch))
    w("")
    w("**How to read a row**")
    w("")
    w("- **Morph** — canon mutation parts (§12, §36.3) assembled by `MorphAssemblyService` as an SPCV client visual "
      "(≤ 24 MeshParts, ≤ 6,000 triangles). `×2` = matched pair (both arms / both legs). Employee rarity is "
      "independent of part rarity; parts drive **traits**, not stats.")
    w("- **Cook · Service · Accuracy · Repair · Combat · Reliability** — the six trainable statistics of canon "
      "§C14.2 on the 1–100 scale, at hire, before candidate variance. Energy, Morale, Salary and Efficiency are "
      "runtime values (§16).")
    w("- **Traits / special abilities** — up to two *derived* traits (from part families/tags, see the Trait "
      "Library in §16) plus one *signature* ability unique to the archetype (italic name). Signature effects that "
      "reference an `ABL_` use that ability's rules from §36.6, retuned for staff (no damage to customers).")
    w("- **Personality** — one of the 14 employee personalities defined in §16 (small morale/energy/mistake modifiers "
      "and report-line flavor).")
    w("- **Training potential** — grade (training gain multiplier) and the stat ceiling reachable by training "
      "(canon potential cap for the rarity; each seniority star adds +3, max 100).")
    w("- **Availability** — the lowest restaurant tier (and the player level that tier requires per §C6) at which the "
      "archetype can appear in the candidate pool; it is the later of the role's unlock tier and the rarity's "
      "first pool tier (§16).")
    w("")
    # brief examples
    w("**Brief examples → archetypes**")
    w("")
    w("| Brief example | Archetype | Why it plays like the brief says |")
    w("|---|---|---|")
    ex = [("Octopus Chef", "EMP_005", "Multi-Tasker: two station slots at once online, ×1.25 offline kitchen contribution"),
          ("Cheetah Waiter", "EMP_028", "Speedster: +35 % walk speed online, ×1.20 offline service contribution"),
          ("Rhino Security Guard", "EMP_066", "Bouncer + Heavyweight: +25 % intercept calm chance, +0.10 offline Security Mitigation"),
          ("Spider Repair Technician", "EMP_058", "Wall Crawler: no ladders, −40 % travel between jobs, +10 pp offline auto-repair discount"),
          ("Robot Cashier", "EMP_034", "Calculator Brain: 0.5 s transactions, cashier skill ×1.5 for the offline tip bonus"),
          ("Sloth Dishwasher", "EMP_039", "Unhurried: 0.6× speed, 0.5× Energy drain, band-minimum hire (200 MB) and wage (10 MB/h)"),
          ("Dragon Chef", "EMP_009", "Grill Master (dragon): grill handling ×0.7 and Perfect +15 %, but 6 % burn chance; offline ×1.15 kitchen, q −0.02")]
    for name, eid, why in ex:
        a = next(x for x in arch if x["id"] == eid)
        w("| %s | `%s` %s | %s |" % (name, eid, a["name"], why))
    w("")
    # coverage
    w("**Coverage (archetypes per role × rarity)**")
    w("")
    w("| Role | Role ID | " + " | ".join("%s %s" % (ICON[r], r) for r in RARITIES) + " | Total |")
    w("|---|---|" + "---|" * (len(RARITIES) + 1))
    for role, rn in ROLE_NAME.items():
        cnt = Counter(a["rarity"] for a in arch if a["role"] == role)
        w("| %s | `%s` | " % (rn, role) + " | ".join(str(cnt.get(r, 0)) for r in RARITIES) +
          " | %d |" % sum(cnt.values()))
    tot = Counter(a["rarity"] for a in arch)
    w("| **All roles** | — | " + " | ".join("**%d**" % tot.get(r, 0) for r in RARITIES) + " | **%d** |" % len(arch))
    w("")
    # main table
    w("#### 36.8.1 Archetype table")
    w("")
    w("| ID | Name | Morph | Role | Rarity | Hire (MB) | Wage (MB/h) | Cook | Service | Accuracy | Repair | Combat | "
      "Reliability | Traits / special abilities | Personality | Training potential | Availability |")
    w("|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|")
    gm = DATA["potential_grade_mult"]
    for a in arch:
        s = a["stats"]
        sig_name, _, sig_eff = a["signature"].partition(":")
        traits = " · ".join(a["traits"]) if a["traits"] else "—"
        tcell = "%s · *%s:*%s" % (traits, sig_name.strip(), sig_eff)
        hire = "0 (tutorial gift, `QST_TUT_012`)" if a["id"] == "EMP_001" else money(a["hire"])
        pot = "%s (×%.2f) · cap %d" % (a["potential_grade"], gm[a["potential_grade"]], a["potential_cap"])
        av = "`TIER_%02d`+ · L%d" % (a["min_tier"], a["min_level"])
        if a["id"] == "EMP_001":
            av = "Tutorial only (`QST_TUT_012`); never in the pool"
        w("| `%s` | %s | %s | `%s` | %s %s | %s | %d | %d | %d | %d | %d | %d | %d | %s | %s | %s | %s |" % (
            a["id"], a["name"], morph_cell(a["parts"]), a["role"], ICON[a["rarity"]], a["rarity"], hire, a["wage"],
            s["cook"], s["svc"], s["acc"], s["rep"], s["cmb"], s["rel"], tcell, a["personality"], pot, av))
    w("")
    # derived reference stats
    w("#### 36.8.2 Role averages at hire (for balancing)")
    w("")
    w("RoleStatAvg uses the role weights of §16 (e.g. Chef = 0.6 Cook + 0.3 Accuracy + 0.1 Reliability). The table "
      "shows the mean RoleStatAvg of this database's archetypes in their native role and the resulting offline "
      "Eff at Morale 80 / Energy 100 / player EFFICIENCY 0 (`Eff = RoleStatAvg × 0.92 / 100`, §17).")
    w("")
    w("| Rarity | Mean native RoleStatAvg | Mean Eff (Morale 80, Energy 100) | Mean hire (MB) | Mean wage (MB/h) | Count |")
    w("|---|---|---|---|---|---|")
    rw = DATA["role_weights"]
    for r in RARITIES:
        rows = [a for a in arch if a["rarity"] == r and a["id"] != "EMP_001"]
        rsa = [sum(a["stats"][k] * v for k, v in rw[a["role"]].items()) for a in rows]
        m = sum(rsa) / len(rsa)
        w("| %s %s | %.1f | %.2f | %s | %s | %d |" % (
            ICON[r], r, m, m * 0.92 / 100, money(int(round(sum(a["hire"] for a in rows) / len(rows), -1))),
            money(int(round(sum(a["wage"] for a in rows) / len(rows)))), len(rows)))
    w("")
    w("#### 36.8.3 Content notes")
    w("")
    w("- **Sloth look.** Canon §C13.6 has no sloth family, so `EMP_039` \"Sloane\" is assembled from a bear head, "
      "moss fur, mitten paws and a turtle neck (the moss is the joke). Her *Unhurried* trait derives from the "
      "turtle family / ≥ 2 `tank` tags with no `speed` tag. If §12 later adds a sloth part, swap the visual only.")
    w("- **Names** are original puns; no real people, brands or existing characters. Report lines use the first "
      "name in quotes when present (\"Ollie\"), otherwise the first word of the name.")
    w("- **Adding archetypes:** append to the JSON with the next free `EMP_` number, run the renderer; it refuses "
      "out-of-band values, illegal slot combinations and traits whose family/tag key is not present. IDs are never "
      "reused (§C2).")
    w("")
    txt = "\n".join(L)
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(txt)
    print("wrote %s (%d bytes, %d archetypes)" % (OUT, len(txt.encode("utf-8")), len(arch)))


if __name__ == "__main__":
    main()
